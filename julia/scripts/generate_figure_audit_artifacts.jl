function _parse_csv(path::AbstractString)
    lines = readlines(path)
    isempty(lines) && error("empty CSV: $path")
    header = split(first(lines), ',')
    length(unique(header)) == length(header) || error("duplicate CSV header: $path")
    rows = Dict{String,String}[]
    for line in Iterators.drop(lines, 1)
        isempty(strip(line)) && continue
        fields = split(line, ','; keepempty = true)
        length(fields) == length(header) || error("malformed CSV row in $path")
        push!(rows, Dict(header .=> fields))
    end
    return rows
end

function _exact(value::AbstractString)
    isempty(value) && error("empty exact rational")
    parts = split(value, "//")
    length(parts) == 1 && return parse(BigInt, only(parts)) // BigInt(1)
    length(parts) == 2 || error("invalid exact rational: $value")
    return parse(BigInt, parts[1]) // parse(BigInt, parts[2])
end

function _tex_exact(value::AbstractString)
    rational = _exact(value)
    denominator(rational) == 1 && return string(numerator(rational))
    return "\\\\frac{$(numerator(rational))}{$(denominator(rational))}"
end

_decimal(value; digits::Integer = 5) = string(round(Float64(value); digits))
_map(value, minimum, maximum, origin, span) =
    origin + span * (Float64(value) - Float64(minimum)) /
        (Float64(maximum) - Float64(minimum))

function _only_row(rows, key::AbstractString, value::AbstractString)
    selected = filter(row -> row[key] == value, rows)
    length(selected) == 1 || error("expected one row with $key=$value")
    return only(selected)
end

function _validate_bridge_rows(rows)
    length(rows) == 5 || error("bridge data must contain five entities")
    expected = Dict(
        "s_L" => ("strategy", "3//1", "1//1", "", ""),
        "s_R" => ("strategy", "1//1", "3//1", "", ""),
        "s_M" => ("strategy", "1//1", "1//1", "m", ""),
        "q" => ("project", "", "", "", "m"),
        "c" => ("descendant", "4//1", "4//1", "", ""),
    )
    for (entity, values) in expected
        row = _only_row(rows, "entity_id", entity)
        observed = (
            row["entity_type"],
            row["profile_b_minus"],
            row["profile_b_plus"],
            row["module_id"],
            row["requires_module"],
        )
        observed == values || error("bridge entity drift: $entity")
    end
    return rows
end

